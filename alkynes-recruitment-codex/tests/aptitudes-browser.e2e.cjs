const { test } = require('node:test');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
test('aptitude requests keep request processing separate from exam completion and generate editable Kakao messages', async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const context = await browser.newContext({ permissions: ['clipboard-read','clipboard-write'], viewport: { width: 1440, height: 1100 } });
  const page = await context.newPage(); const errors = []; page.on('pageerror', e => errors.push(e.message));
  const base = process.env.E2E_BASE_URL || 'http://127.0.0.1:8793';
  try {
    await page.goto(base + '/aptitudes');
    await page.getByRole('heading', { name: '인적성 관리', exact: true }).waitFor();
    await page.evaluate(() => {
      const stamp = { createdAt: '2026-10-14T00:00:00.000Z', updatedAt: '2026-10-14T00:00:00.000Z' };
      const requisitions = [{ ...stamp, id: 'test-job', code: 'HR-2026-001', department: '검증부서', requester: '', role: '검증공고', headcount: 1, reason: '', duties: '', requirements: '', preferred: '', targetJoin: '', status: '진행중' }];
      const candidates = [{ ...stamp, id: 'test-person', requisitionId: 'test-job', name: '검증지원자', source: '', career: '', phone: '비공유연락처', email: '', status: '검토중', notes: '', resumeName: '', resumeData: '' }];
      const interviews = [{ ...stamp, id: 'test-meeting', candidateId: 'test-person', startsAt: '2099-10-16T05:00:00.000Z', location: '검증회의실', interviewers: ['검증면접관'], status: '면접예정' }];
      localStorage.setItem('alkynes.recruitment.v1', JSON.stringify({ version: 1, requisitions, candidates, interviews, evaluations: [], activity: [], requests: [{ ...stamp, id: 'test-aptitude', requisitionId: 'test-job', candidateId: 'test-person', excelJobId: '', stage: '인적성 검사 요청', round: 1, receivedAt: '2026-10-14T00:00:00.000Z', dueAt: '2026-10-16T09:00:00.000Z', completedAt: '2026-10-15T01:00:00.000Z', status: '요청 완료', examAt: '2026-10-16T05:00:00.000Z', owner: '', notes: '', source: 'kpi-excel' }] }));
    });
    await page.reload();
    const nav = await page.locator('aside nav a').allTextContents(); assert.deepEqual(nav.slice(-2), ['엑셀 연동','설정']);
    assert.equal(await page.getByRole('button', { name: '+ 인적성 요청 등록', exact: true }).count(), 0);
    await page.getByRole('button', { name: '상세 / 수정', exact: true }).click();
    const dialog = page.getByRole('dialog');
    assert.equal(await dialog.locator('select[name=candidateId]').inputValue(), 'test-person');
    for (const name of ['receivedAt','dueAt','completedAt','examAt','owner']) assert.equal(await dialog.locator('input[name=' + name + ']').isDisabled(), true);
    assert.equal(await dialog.locator('select[name=status]').isDisabled(), true);
    await dialog.locator('input[name=examDeadline]').fill('2026-10-19T18:00');
    await dialog.locator('select[name=examStatus]').selectOption('검사예정');
    await dialog.locator('textarea[name=notes]').fill('공유금지 내부 메모');
    await dialog.getByRole('button', { name: '저장', exact: true }).click();
    await page.getByText('요청: 요청 완료', { exact: true }).waitFor();
    await page.getByText('검사: 검사예정', { exact: true }).waitFor();
    assert.equal(await page.getByRole('button', { name: '카톡 안내문', exact: true }).count(), 1);
    await page.getByRole('button', { name: '카톡 안내문 작성', exact: true }).click();
    await page.getByLabel('안내문 대상', { exact: true }).selectOption('test-aptitude');
    await page.getByRole('button', { name: '안내문 열기', exact: true }).click();
    const share = page.getByRole('dialog', { name: '인적성 카톡 안내문', exact: true });
    const content = share.getByLabel('공유 안내문', { exact: true });
    assert.ok((await content.inputValue()).includes('검증지원자'));
    assert.ok(!(await content.inputValue()).includes('공유금지'));
    assert.ok(!(await content.inputValue()).includes('비공유연락처'));
    assert.equal(await share.getByLabel('공유 대상').count(), 0);
    assert.ok((await content.inputValue()).includes('요청 완료했습니다.'));
    assert.ok((await content.inputValue()).includes('응시기한: 2026년 10월 19일'));
    assert.ok(!/처리기한|검사 일정|실시 상태|회차|회신/.test(await content.inputValue()));
    await content.fill((await content.inputValue()) + '\n검증용 추가 안내');
    await share.getByRole('button', { name: '카톡 메시지 복사', exact: true }).click();
    await share.getByText('복사했습니다. 카카오톡에 전송한 뒤 안내 완료로 표시해 주세요.', { exact: true }).waitFor();
    assert.ok((await page.evaluate(() => navigator.clipboard.readText())).includes('검증용 추가 안내'));
    await share.getByRole('button', { name: '닫기', exact: true }).last().click();
    await page.getByRole('button', { name: '상세 / 수정', exact: true }).click();
    await dialog.locator('select[name=examStatus]').selectOption('실시완료');
    await dialog.getByRole('button', { name: '저장', exact: true }).click();
    assert.equal(await page.getByRole('button', { name: '상세 / 수정', exact: true }).count(), 0);
    await page.getByRole('button', { name: /^완료·종료/ }).click();
    await page.getByText('검사: 실시완료', { exact: true }).waitFor();
    await page.reload(); await page.getByRole('button', { name: /^완료·종료/ }).click();
    await page.getByText('검사: 실시완료', { exact: true }).waitFor();
    await page.screenshot({ path: '/workspace/scratch/aptitudes-management.png', fullPage: true });
    await page.goto(base + '/interviews');
    await page.getByRole('button', { name: '카톡 안내문', exact: true }).click();
    const interviewShare = page.getByRole('dialog', { name: '면접 일정 카톡 안내문', exact: true });
    await interviewShare.getByLabel('공유 대상').selectOption('candidate');
    const text = await interviewShare.getByLabel('공유 안내문', { exact: true }).inputValue();
    assert.ok(text.includes('(주) 알킨스 사무동 3층 영업부 회의실')); assert.ok(text.includes('청북중앙로 578-19')); assert.ok(text.startsWith('안녕하세요, 알킨스 경영지원팀 민성진 과장입니다.')); assert.ok(!text.includes('회신')); assert.ok(!text.includes('검증면접관'));
    await interviewShare.getByRole('button', { name: '닫기', exact: true }).last().click();
    await page.setViewportSize({ width: 1280, height: 720 });
    const quick = await page.getByLabel('빠른 업데이트', { exact: true }).boundingBox();
    assert.ok(quick && quick.y >= 0 && quick.y + quick.height <= 720);
    assert.deepEqual(errors, []);
  } finally { await browser.close(); }
});
